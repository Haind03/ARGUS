HEADER = """/*
  ARGUS starter YARA rules, generic, DEFENSIVE, for triage of files on the user's own machine.
  GENERATED by tools/build_yara.py, edit the spec there, not this file.
  Strings are regexes with \\xNN escapes so this file is not itself mistaken for malware by AV.
  Expect false positives (security tools, browsers, scripts), treat hits as leads (score +30).
*/
"""


def build() -> str:
    parts = [HEADER]
    for name, tech, desc, groups, cond in RULES:
        s = "\n".join(strings(g, items) for g, items in groups.items())
        parts.append(f"""rule {name}
{{
    meta:
        author = "ARGUS"
        description = "{desc}"
        attack = "{tech}"
        scope = "defensive triage"
    strings:
{s}
    condition:
        filesize < 50MB and ({cond})
}}
""")
