def esc(s: str) -> str:
    out = []
    for i, ch in enumerate(s):
        if i % 3 == 1 and ch.isalnum():
            out.append(f"\\x{ord(ch):02x}")
        elif ch in r"\/.^$|?*+()[]{}":
            out.append("\\" + ch)
        elif ch == " ":
            out.append("\\s")
        else:
            out.append(ch)
    return "".join(out)


def strings(name: str, items: list[str], nocase=True) -> str:
    flag = "i" if nocase else ""
    return "\n".join(f"        ${name}{i} = /{esc(s)}/{flag} ascii wide" for i, s in enumerate(items))


