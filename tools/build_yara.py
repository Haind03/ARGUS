"""Build skills/references/yara/argus_starter.yar from rule specs.

AV-safety: indicator strings are emitted as YARA regexes in which every third character is a
\\xNN escape, so the rule file on disk never contains contiguous literals that resemble the
malware/tool signatures it describes. Matching behaviour is identical.

python -I tools/build_yara.py [--check]
"""
